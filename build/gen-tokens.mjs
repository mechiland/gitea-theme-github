// Generates src/tokens/generated/* from the pinned @primer/primitives package.
// Output is committed so the build is reproducible; re-run after bumping the pin.
//
// - Color tokens: the first (explicit light/dark) block of functional/themes/{light,dark}.css,
//   re-scoped to :root because Gitea's <html> has no data-color-mode attributes.
// - Scale tokens (size, space, radius, border, typography, motion, z-index, breakpoints):
//   base + functional files. rem is converted to px at 16px/rem, because Gitea sets
//   `html { font-size: 14px }` and Primer's rem values assume a 16px root.
// - The --color-ansi-* aliases are dropped: Gitea owns those names (mapped in gitea-map.css).
// - "Mona Sans VF" is removed from the font stacks: we ship no GitHub brand fonts and use the
//   system stack exactly as Primer lists it after that entry.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const pkgDir = path.dirname(require.resolve('@primer/primitives/package.json'));
const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
const dist = path.join(pkgDir, 'dist/css');
const outDir = path.join(root, 'src/tokens/generated');
fs.mkdirSync(outDir, {recursive: true});

const header = `/* GENERATED by build/gen-tokens.mjs from @primer/primitives@${pkg.version} (MIT). Do not edit. */\n`;

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '');
const remToPx = (css) => css.replace(/(-?\d*\.?\d+)rem\b/g, (_, n) => `${+(parseFloat(n) * 16).toFixed(4)}px`);
const noMona = (css) => css.replace(/"Mona Sans VF",\s*/g, '');

function firstBlockDecls(file) {
  const css = stripComments(fs.readFileSync(path.join(dist, file), 'utf8'));
  const open = css.indexOf('{');
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) return css.slice(open + 1, i);
  }
  throw new Error(`unbalanced ${file}`);
}

function declsToRoot(body, {drop = []} = {}) {
  const lines = body.split(';').map((d) => d.trim()).filter(Boolean)
    .filter((d) => !drop.some((re) => re.test(d)))
    .map((d) => `  ${d.replace(/\s+/g, ' ')};`);
  return {count: lines.length, css: `:root {\n${lines.join('\n')}\n}\n`};
}

const names = {};
for (const scheme of ['light', 'dark']) {
  const {count, css} = declsToRoot(firstBlockDecls(`functional/themes/${scheme}.css`), {drop: [/^--color-ansi-/]});
  fs.writeFileSync(path.join(outDir, `primer-color-${scheme}.css`), header + remToPx(css));
  names[scheme] = [...css.matchAll(/^\s*(--[\w-]+):/gm)].map((m) => m[1]);
  console.log(`color ${scheme}: ${count} tokens`);
}
const onlyLight = names.light.filter((n) => !names.dark.includes(n));
const onlyDark = names.dark.filter((n) => !names.light.includes(n));
if (onlyLight.length || onlyDark.length) throw new Error(`light/dark token sets differ: ${onlyLight} | ${onlyDark}`);

const scaleFiles = [
  'base/size/size.css', 'base/size/z-index.css', 'base/typography/typography.css', 'base/motion/motion.css',
  'functional/size/border.css', 'functional/size/radius.css', 'functional/size/size.css',
  'functional/size/size-fine.css', 'functional/size/size-coarse.css', 'functional/size/breakpoints.css',
  'functional/size/z-index.css', 'functional/spacing/space.css', 'functional/typography/typography.css',
  'functional/motion/motion.css',
];
let scale = '';
for (const f of scaleFiles) scale += `/* ${f} */\n${stripComments(fs.readFileSync(path.join(dist, f), 'utf8')).replace(/\n\s*\n/g, '\n').trim()}\n`;
scale = noMona(remToPx(scale));
fs.writeFileSync(path.join(outDir, 'primer-scale.css'), header + scale);

// Allowed-color list for the screenshot tool / lint (every literal color value Primer emits).
const allColors = new Set();
for (const scheme of ['light', 'dark']) {
  const css = fs.readFileSync(path.join(outDir, `primer-color-${scheme}.css`), 'utf8');
  for (const m of css.matchAll(/#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)/g)) allColors.add(m[0].toLowerCase());
}
fs.writeFileSync(path.join(outDir, 'primer-literal-colors.json'), JSON.stringify([...allColors].sort(), null, 1));
fs.writeFileSync(path.join(outDir, 'VERSION'), `@primer/primitives ${pkg.version}\n`);
console.log(`scale tokens written; ${allColors.size} distinct literal colors; primitives ${pkg.version}`);
